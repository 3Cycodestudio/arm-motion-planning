# ================= 5 讨论 =================
H("5 讨论", 1)
P("三点值得讨论的发现。其一，边级碰撞检查不可省略：高维空间中扩展步长与障碍薄截面同量级时，"
  "仅验证节点会系统性漏检穿障，本研究的严格复核环节（路径插值重检）是结果可信度的必要保障。"
  "其二，学习模块的超参数须数据驱动：固定衰减尺度在六维下导致标签整体趋零、网络拟合失效（相关系数 -0.254），"
  "改为按距离分布分位数取值后跃升至 0.945。其三，学习引导的边际收益随维度与场景而变：二维下节点压缩至 72%，"
  "六维下为 82.8%——静态环境中 10% 目标偏置已使 RRT 具备相当探索效率，学习先验的增益空间相应收窄；"
  "可预期在动态环境或狭窄通道密集场景中收益回升，此为后续方向。", draft=True)
P("连通性认识：抽样算法只解决“找路”，可行性由问题本身决定——C 空间被障碍切成不连通两块时，"
  "任何撒点策略都无法成功（二维反例实验：1939 次撒点仍失败）。")

