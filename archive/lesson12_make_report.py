import os
from docx import Document
from docx.shared import Cm, Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "lesson12_report_draft.docx")

doc = Document()

def H(text, level):
    doc.add_heading(text, level=level)

def P(text, draft=False):
    p = doc.add_paragraph(text + ("（草稿）" if draft else ""))
    return p

def PIC(name, caption, width=15.5):
    path = os.path.join(HERE, name)
    if os.path.exists(path):
        doc.add_picture(path, width=Cm(width))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        cap = doc.add_paragraph(caption)
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        for r in cap.runs:
            r.font.size = Pt(9)

# ================= 摘要 =================
H("摘要", 1)
P("针对复杂受限环境下多自由度机械臂的运动规划与轨迹生成问题，本研究以基于学习和抽样的混合规划算法为主线，"
  "构建了从建模、规划、优化到学习引导的完整算法链。二维两连杆模型作为方法验证教学案例，验证了网格搜索(BFS)、"
  "快速探索随机树(RRT)、路径平滑、渐近最优RRT*、梯形速度时间参数化与学习引导抽样各环节的正确性；"
  "随后将全链迁移至开源物理引擎 PyBullet 中的 Franka Panda 真实机器人模型（冻结第七关节等效六自由度），"
  "在含墙与立柱的受限场景中完成六维关节空间规划：RRT 以 1393 次碰撞检查完成规划，探索量约为六维网格穷举"
  "（5.2×10^12 格）的 37 亿分之一；学习引导抽样将树节点数进一步压缩至均匀采样的 82.8%。"
  "所有路径均通过边级插值严格复核，零碰撞。", draft=True)

