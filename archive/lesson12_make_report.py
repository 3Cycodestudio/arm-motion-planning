  "六维关节空间的组合规模随自由度指数增长——按 2° 分辨率穷举需遍历约 5.2×10^12 个构型，"
  "网格类确定性算法在高维下完全不可行；其二，受限环境中障碍将可行空间切割成狭长通道，"
  "均匀随机抽样的探索效率随通道变窄而急剧下降。前者决定了必须采用抽样规划，"
